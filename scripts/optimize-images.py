"""Generate display copies without changing original artwork. Requires Pillow."""
from pathlib import Path
import json
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
manifest = {}
original_bytes = generated_bytes = 0
for source in sorted((ROOT / "images").rglob("*")):
    if "optimized" in source.parts or source.suffix.lower() not in {".png", ".jpg", ".jpeg"}:
        continue
    relative = source.relative_to(ROOT)
    original_bytes += source.stat().st_size
    with Image.open(source) as opened:
        image = ImageOps.exif_transpose(opened)
        if image.mode not in ("RGB", "RGBA"):
            image = image.convert("RGB")
        entry = {"width": image.width, "height": image.height, "variants": []}
        for size in (480, 960, 1920):
            destination = ROOT / "images" / "optimized" / relative.relative_to("images").with_suffix("")
            destination = destination.with_name(f"{destination.name}-{size}.webp")
            destination.parent.mkdir(parents=True, exist_ok=True)
            width = min(size, image.width)
            height = round(image.height * width / image.width)
            if not destination.exists() or destination.stat().st_mtime < source.stat().st_mtime:
                resized = image.resize((width, height), Image.Resampling.LANCZOS)
                resized.save(destination, "WEBP", quality=84, method=6)
            generated_bytes += destination.stat().st_size
            entry["variants"].append({"src": destination.relative_to(ROOT).as_posix(), "width": width})
        manifest[relative.as_posix()] = entry
(ROOT / "assets" / "image-manifest.js").write_text(
    "// Generated by scripts/optimize-images.py. Do not edit manually.\n"
    "window.portfolioImages = " + json.dumps(manifest, ensure_ascii=False, indent=2) + ";\n",
    encoding="utf-8",
)
print(json.dumps({"images": len(manifest), "original_bytes": original_bytes, "all_display_copies_bytes": generated_bytes}))
